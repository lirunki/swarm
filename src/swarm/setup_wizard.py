MAX_CONFIG = 64 * 1024
BINDS = {"127.0.0.1", "localhost", "::1", "0.0.0.0", "::"}
GENERATED = "# Generated by Swarm setup; no credentials are embedded.\n"


class SetupError(ValueError):
    pass


class Console:
    def say(self, text):
        print(text, flush=True)

    def ask(self, label, default=None):
        suffix = f" [{default}]" if default is not None else ""
        value = input(label + suffix + ": ").strip()
        if len(value) > 4096 or any(ord(c) < 32 for c in value):
            raise SetupError("Input is too long or contains control characters.")
        return value or (str(default) if default is not None else "")

    def yes(self, label, default=False):
        while True:
            value = self.ask(label + (" [Y/n]" if default else " [y/N]")).lower()
            if not value:
                return default
            if value in ("y", "yes"):
                return True
            if value in ("n", "no"):
                return False
            self.say("Please answer yes or no.")

    def secret(self, label):
        if not sys.stdin.isatty():
            raise SetupError(
                "Hidden secret input requires a terminal. Use existing private credential files for non-interactive input."
            )
        return getpass.getpass(label + ": ")


def absolute(value):
    if not isinstance(value, str) or not value or any(ord(c) < 32 for c in value):
        raise SetupError("A nonempty path without control characters is required.")
    return str(Path(value).expanduser().absolute())


def private_file(path, *, limit=MAX_CONFIG):
    path = Path(path)
    info = path.lstat()
    if path.is_symlink() or not path.is_file() or info.st_size > limit:
        raise SetupError("Expected a bounded regular file, not a symbolic link.")
    if os.name != "nt" and info.st_mode & 0o077:
        raise SetupError("Private files must have owner-only permissions (0600).")
    return path


def write_private(path, text, *, replace=False):
    """Exclusive creation or atomic explicit replacement; never follow a final symlink."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    if path.is_symlink():
        raise SetupError("Refusing to write through a symbolic link.")
    if path.exists():
        private_file(path)
        if not replace:
            raise SetupError("File already exists; choose a new path or reuse it explicitly.")
    if not replace:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            output.write(text)
            output.flush()
            os.fsync(output.fileno())
        return
    fd, temporary = tempfile.mkstemp(prefix=".swarm-setup-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            output.write(text)
            output.flush()
            os.fsync(output.fileno())
        if path.is_symlink():
            raise SetupError("Refusing to replace a symbolic link.")
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def _fields(value, fields, label):
    if not isinstance(value, dict) or set(value) != set(fields):
        raise SetupError(f"Invalid {label} configuration fields.")


def _saved_path(value):
    if (
        not isinstance(value, str)
        or not Path(value).is_absolute()
        or any(ord(c) < 32 for c in value)
    ):
        raise SetupError("Saved paths must be absolute and contain no control characters.")


def _port(value):
    if type(value) is not int or not 1 <= value <= 65535:
        raise SetupError("Port must be an integer between 1 and 65535.")


def _tls(value):
    if value is None:
        return
    _fields(value, {"certfile", "keyfile"}, "TLS")
    for path in value.values():
        _saved_path(path)
    if value["certfile"] == value["keyfile"]:
        raise SetupError("Certificate and private-key paths must differ.")


