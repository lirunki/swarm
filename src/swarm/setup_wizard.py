def check_service_path(path, home):
    try:
        relative = Path(path).resolve().relative_to(Path(home).resolve())
    except ValueError:
        return
    if relative.parts and relative.parts[0] in SERVICE_PATHS:
        raise SetupError(
            "Setup/credential files must not occupy Swarm-managed registry state paths."
        )


def validate_config(config):
    _fields(
        config,
        {
            "version",
            "runtime_dir",
            "source_dir",
            "pi",
            "path_entries",
            "home",
            "relay",
            "server",
            "launch_roles",
        },
        "setup",
    )
    if type(config["version"]) is not int or config["version"] != 1:
        raise SetupError("Unsupported setup configuration version.")
    for field in ("runtime_dir", "source_dir", "pi", "home"):
        _saved_path(config[field])
    if not isinstance(config["path_entries"], list) or len(config["path_entries"]) > 16:
        raise SetupError("Invalid runtime PATH entries.")
    for path in config["path_entries"]:
        _saved_path(path)
    relay = config["relay"]
    if relay is not None:
        _fields(relay, {"host", "port", "tls", "api_key_file", "advertise_host"}, "repeater")
        if relay["host"] not in BINDS:
            raise SetupError("Unsupported repeater bind address.")
        _port(relay["port"])
        _tls(relay["tls"])
        _saved_path(relay["api_key_file"])
        if relay["tls"] is None:
            raise SetupError("A repeater always requires TLS.")
        _advertise_host(relay["advertise_host"])
    server = config["server"]
    if server is not None:
        _fields(
            server,
            {
                "host",
                "port",
                "tls",
                "password_file",
                "connection",
                "recover",
                "allow_remote_restart",
                "allow_saved_relay_settings",
            },
            "server",
        )
        if server["host"] not in BINDS - {"::"}:
            raise SetupError("Unsupported dashboard bind address.")
        _port(server["port"])
        _tls(server["tls"])
        for field in ("recover", "allow_remote_restart", "allow_saved_relay_settings"):
            if type(server[field]) is not bool:
                raise SetupError("Server policies must be booleans.")
        if server["password_file"] is not None:
            _saved_path(server["password_file"])
        connection = server["connection"]
        if connection is not None:
            _fields(
                connection,
                {"url", "node_id", "name", "api_key_file", "ca_file"},
                "relay connection",
            )
            if (
                not isinstance(connection["url"], str)
                or urlsplit(connection["url"]).scheme != "wss"
            ):
                raise SetupError("Relay connections must use wss:// with an explicit endpoint.")
            try:
                FederationConfig(
                    url=connection["url"],
                    node_id=connection["node_id"],
                    name=connection["name"],
                    api_key="x" * 48,
                    local_api_url="http://127.0.0.1:8787",
                ).validate()
            except (ValueError, TypeError, AttributeError):
                raise SetupError(
                    "Invalid relay URL or node identity; do not put secrets in URLs."
                ) from None
            _saved_path(connection["api_key_file"])
            if connection["ca_file"] is not None:
                _saved_path(connection["ca_file"])
            if server["password_file"] is None:
                raise SetupError("A relay-connected dashboard requires a browser password.")
        if server["allow_remote_restart"] and connection is None:
            raise SetupError("Remote restart requires an explicit relay connection.")
        if server["allow_saved_relay_settings"] and not server["password_file"]:
            raise SetupError("Saved relay profiles require a browser password too.")
        if server["host"] == "0.0.0.0" and (not server["tls"] or not server["password_file"]):
            raise SetupError("Network dashboard access requires TLS and a browser password.")
        if relay and relay["port"] == server["port"]:
            raise SetupError("Choose different repeater and dashboard ports.")
    roles = config["launch_roles"]
    if (
        not isinstance(roles, list)
        or any(not isinstance(role, str) for role in roles)
        or len(set(roles)) != len(roles)
        or any(role not in {"relay", "server"} or config[role] is None for role in roles)
    ):
        raise SetupError("Invalid saved launch roles; select only configured services.")
    if server and server["password_file"]:
        password = Path(server["password_file"]).resolve()
        keys = [relay["api_key_file"]] if relay else []
        if server["connection"]:
            keys.append(server["connection"]["api_key_file"])
        if any(Path(key).resolve() == password for key in keys):
            raise SetupError("Browser passwords and relay API keys must use separate files.")
    for path in referenced_files(config):
        check_service_path(path, config["home"])
    return config


def referenced_files(config):
    paths = []
    for service in (config["relay"], config["server"]):
        if not service:
            continue
        for field in ("api_key_file", "password_file"):
            if service.get(field):
                paths.append(service[field])
        if service.get("tls"):
            paths.extend(service["tls"].values())
    if config["server"] and config["server"]["connection"]:
        connection = config["server"]["connection"]
        paths.extend(
            value
            for key, value in connection.items()
            if key in {"api_key_file", "ca_file"} and value
        )
    return {Path(value).resolve() for value in paths}


def check_output_paths(path, config):
    path = Path(path)
    check_service_path(path, config["home"])
    check_service_path(path.with_suffix(".run.sh"), config["home"])
    if referenced_files(config) & {path.resolve(), path.with_suffix(".run.sh").resolve()}:
        raise SetupError(
            "Setup JSON/launch script paths must not overlap any credential or TLS file."
        )


def read_config(path):
    path = private_file(path)
    try:
        config = json.loads(path.read_text(encoding="utf-8"))
        return validate_config(config)
    except (ValueError, TypeError, KeyError, AttributeError):
        raise SetupError("Invalid saved setup JSON; it was not changed.") from None


def save_config(path, config, *, replace=False):
    validate_config(config)
    check_output_paths(path, config)
    write_private(path, json.dumps(config, indent=2, ensure_ascii=False) + "\n", replace=replace)


def _advertise_host(value):
    if not isinstance(value, str) or not value:
        raise SetupError("A client-visible hostname or IP is required.")
    try:
        address = ipaddress.ip_address(value)
        if address.is_unspecified:
            raise SetupError("A wildcard bind address is not a client endpoint.")
    except ValueError as error:
        if isinstance(error, SetupError):
            raise
        # Existing SAN validation rejects URLs, config injection, wildcards and bad DNS.
        certificate_names([value])
    return value


def _url_host(host):
    return "[" + host + "]" if ":" in host else host


def ask_port(console, label, default):
    while True:
        try:
            value = int(console.ask(label, default))
            _port(value)
            return value
        except ValueError:
            console.say("Enter a port between 1 and 65535.")


def ask_bind(console, label, *, dashboard=False):
    choices = BINDS - ({"::"} if dashboard else set())
    while True:
        value = console.ask(label + " (" + ", ".join(sorted(choices)) + ")", "127.0.0.1")
        if value in choices:
            return value
        console.say("Select one of the listed bind addresses.")


def choose_tls(console, directory, host, *, home=None):
    generate = console.yes("Generate a self-signed TLS certificate if absent?", True)
    cert = Path(absolute(console.ask("TLS certificate file", str(directory / "cert.pem"))))
    key = Path(absolute(console.ask("TLS private-key file", str(directory / "privkey.pem"))))
    if home:
        check_service_path(cert, home)
        check_service_path(key, home)
    if generate:
        extra = console.ask("Certificate DNS names/IPs (comma-separated)", host)
        hosts = [host, *[part.strip() for part in extra.split(",") if part.strip()]]
        days = ask_port(console, "Certificate validity in days", 365)
        if days > 36500:
            raise SetupError("Certificate validity cannot exceed 36500 days.")
        generate_if_absent(cert, key, hosts=hosts, days=days)
        console.say(
            "Self-signed TLS is not automatically trusted. Distribute only the public certificate to clients; never the private key."
        )
    private_file(key)
    if cert.is_symlink() or not cert.is_file():
        raise SetupError("TLS certificate must be an existing regular file.")
    ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER).load_cert_chain(cert, key)
    return {"certfile": str(cert), "keyfile": str(key)}


def choose_key(console, default, *, allow_generate=True, home=None):
    path = Path(absolute(console.ask("Relay API-key file", str(default))))
    if home:
        check_service_path(path, home)
    if path.exists() or path.is_symlink():
        private_file(path, limit=4096)
        if not console.yes("Reuse this existing key file without changing it?", True):
            raise SetupError("Key file was not changed; rerun with a new path.")
    elif allow_generate and console.yes("Generate a new random relay API key?", True):
        write_private(path, secrets.token_urlsafe(48) + "\n")
    else:
        value = console.secret("Relay API key (hidden; at least 32 printable ASCII characters)")
        _key_value(value)
        write_private(path, value + "\n")
    _key_value(path.read_text(encoding="utf-8").strip())
    console.say(
        "Relay key is stored privately; securely copy the key file when configuring another controller. Its value is not printed."
    )
    return str(path)


def _key_value(value):
    if not 32 <= len(value) <= 4096 or any(not 33 <= ord(c) <= 126 for c in value):
        raise SetupError("Relay API key must be 32–4096 printable ASCII characters without spaces.")


def choose_password(console, default, *, home=None):
    path = Path(absolute(console.ask("Browser password file", str(default))))
    if home:
        check_service_path(path, home)
    if path.exists() or path.is_symlink():
        private_file(path, limit=4096)
        if not console.yes("Reuse this existing password file without changing it?", True):
            raise SetupError("Password file was not changed; rerun with a new path.")
    else:
        value = console.secret("New browser password (hidden; at least 8 characters)")
        if not 8 <= len(value) <= 1024 or any(ord(c) < 32 or ord(c) == 127 for c in value):
            raise SetupError("Use 8–1024 characters without control characters.")
        if console.secret("Confirm browser password") != value:
            raise SetupError("Passwords did not match; no password was saved.")
        write_private(path, value + "\n")
    from .auth import password_bytes

    password_bytes(path)
    return str(path)


def collect_config(console, *, runtime_dir, source_dir, pi, config_path):
    directory = config_path.parent
    home = absolute(console.ask("Swarm registry/data directory", str(Path.home() / ".swarm")))
    check_service_path(config_path, home)
    check_service_path(config_path.with_suffix(".run.sh"), home)
    allow_saved = False
    if (Path(home) / "relay-settings.json").exists():
        console.say(
            "This registry has saved dashboard relay Settings. Those can override setup connection choices; no saved settings will be changed."
        )
        allow_saved = console.yes(
            "Explicitly allow those existing dashboard relay settings?", False
        )
        if not allow_saved:
            raise SetupError(
                "Choose a different registry or intentionally update its dashboard relay Settings first."
            )
    relay = None
    if console.yes("Configure a local repeater (federation relay) on this machine?", False):
        host = ask_bind(console, "Repeater bind address")
        port = ask_port(console, "Repeater port", 9443)
        advertise = _advertise_host(
            console.ask("Hostname/IP controllers will use to reach this repeater", "localhost")
        )
        tls = choose_tls(console, directory / "tls" / "repeater", advertise, home=home)
        key = choose_key(console, directory / "relay.key", home=home)
        relay = {
            "host": host,
            "port": port,
            "advertise_host": advertise,
            "tls": tls,
            "api_key_file": key,
        }
    server = None
    if console.yes("Configure a Swarm dashboard/server on this machine?", True):
        host = ask_bind(console, "Dashboard bind address", dashboard=True)
        port = ask_port(console, "Dashboard port", 8787)
        tls = None
        if host == "0.0.0.0" or console.yes("Use HTTPS for the dashboard?", False):
            advertise = _advertise_host(
                console.ask("Dashboard hostname/IP for its certificate", "localhost")
            )
            tls = choose_tls(console, directory / "tls" / "dashboard", advertise, home=home)
        connection = None
        if relay:
            connect = console.yes("Connect this server to the local repeater?", True)
        else:
            connect = console.yes("Connect this server to an existing repeater?", False)
        if connect:
            if relay:
                url = f"wss://{_url_host(relay['advertise_host'])}:{relay['port']}/v1/connect"
                key = relay["api_key_file"]
                ca = relay["tls"]["certfile"]
                console.say(
                    "Using the explicitly configured local repeater endpoint and public certificate."
                )
            else:
                url = console.ask("Existing repeater WebSocket URL (wss://host:port/v1/connect)")
                # Validate before ever prompting for or saving credentials for a bad URL.
                try:
                    if urlsplit(url).scheme != "wss":
                        raise ValueError()
                    FederationConfig(
                        url=url,
                        node_id="setup-check",
                        name="Setup",
                        api_key="x" * 48,
                        local_api_url="http://127.0.0.1:8787",
                    ).validate()
                except ValueError:
                    raise SetupError(
                        "A valid explicit wss:// endpoint without credentials/query/fragment is required."
                    ) from None
                console.say(
                    "Obtain the existing repeater API key from its operator; a new random key would not authorize this connection."
                )
                key = choose_key(console, directory / "relay.key", allow_generate=False, home=home)
                ca = None
                if not console.yes("Trust this repeater using the system CA store?", True):
                    ca = absolute(console.ask("CA/public certificate file for this repeater"))
                    if Path(ca).is_symlink() or not Path(ca).is_file():
                        raise SetupError("CA certificate must be an existing regular file.")
                    ssl.create_default_context(cafile=ca)
            node = console.ask("Unique relay node ID", "swarm-" + secrets.token_hex(4))
            name = console.ask("Relay display name", socket.gethostname())
            connection = {
                "url": url,
                "node_id": node,
                "name": name,
                "api_key_file": key,
                "ca_file": ca,
            }
        password = None
        required = host == "0.0.0.0" or connection is not None or allow_saved
        if required:
            console.say("A browser password is required for network or relayed access.")
        if required or console.yes("Protect the loopback dashboard with a browser password?", True):
            password = choose_password(console, directory / "browser-password.txt", home=home)
        server = {
            "host": host,
            "port": port,
            "tls": tls,
            "password_file": password,
            "connection": connection,
            "recover": console.yes("Automatically resume saved agents at server startup?", False),
            "allow_remote_restart": bool(
                connection
                and console.yes("Allow authenticated remote controller/agent restarts?", False)
            ),
            "allow_saved_relay_settings": allow_saved,
        }
    entries = [str(Path(runtime_dir) / "venv/bin"), str(Path(pi).parent)]
    import shutil

    node = shutil.which("node")
    if node:
        entries.append(str(Path(node).parent))
    config = {
        "version": 1,
        "runtime_dir": str(runtime_dir),
        "source_dir": str(source_dir),
        "pi": str(pi),
        "path_entries": list(dict.fromkeys(entries)),
        "home": home,
        "relay": relay,
        "server": server,
        "launch_roles": [],
    }
    return validate_config(config)


def service_commands(config):
    validate_config(config)
    base = [
        str(Path(config["runtime_dir"]) / "venv/bin/python"),
        "-m",
        "swarm",
        "--home",
        config["home"],
    ]
    result = {}
    relay = config["relay"]
    if relay:
        result["relay"] = [
            *base,
            "relay",
            "serve",
            "--host",
            relay["host"],
            "--port",
            str(relay["port"]),
            "--certfile",
            relay["tls"]["certfile"],
            "--keyfile",
            relay["tls"]["keyfile"],
            "--api-key-file",
            relay["api_key_file"],
        ]
    server = config["server"]
    if server:
        args = [
            *base,
            "serve",
            "--host",
            server["host"],
            "--port",
            str(server["port"]),
            "--pi",
            config["pi"],
        ]
        if not server["recover"]:
            args.append("--no-recover")
        if server["tls"]:
            args += ["--certfile", server["tls"]["certfile"], "--keyfile", server["tls"]["keyfile"]]
        if server["password_file"]:
            args += ["--password-file", server["password_file"]]
        if server["allow_remote_restart"]:
            args.append("--allow-remote-restart")
        if server["connection"]:
            c = server["connection"]
            args += [
                "--relay-url",
                c["url"],
                "--relay-node-id",
                c["node_id"],
                "--relay-name",
                c["name"],
                "--relay-api-key-file",
                c["api_key_file"],
            ]
        result["server"] = args
    return result


def service_environment(config, role):
    environment = {
        key: value
        for key, value in os.environ.items()
        if not key.startswith("SWARM_RELAY_") and key not in {"SSL_CERT_FILE", "SSL_CERT_DIR"}
    }
    environment["PATH"] = os.pathsep.join([*config["path_entries"], environment.get("PATH", "")])
    environment["VIRTUAL_ENV"] = str(Path(config["runtime_dir"]) / "venv")
    if (
        role == "server"
        and config["server"]["connection"]
        and config["server"]["connection"]["ca_file"]
    ):
        environment["SSL_CERT_FILE"] = config["server"]["connection"]["ca_file"]
    return environment


def preflight(config, selected):
    """Fail before spawning anything; never kill or blindly reuse a listener."""
    if (
        "server" in selected
        and (Path(config["home"]) / "relay-settings.json").exists()
        and not config["server"]["allow_saved_relay_settings"]
    ):
        raise SetupError(
            "Saved dashboard relay Settings now exist; rerun setup to acknowledge them or choose another registry."
        )
    for role in selected:
        service = config["relay" if role == "relay" else "server"]
        for field in ("api_key_file", "password_file"):
            if service.get(field):
                private_file(service[field], limit=4096)
                if field == "api_key_file":
                    _key_value(Path(service[field]).read_text(encoding="utf-8").strip())
                else:
                    from .auth import password_bytes

                    password_bytes(Path(service[field]))
        if service.get("tls"):
            tls = service["tls"]
            private_file(tls["keyfile"])
            ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER).load_cert_chain(tls["certfile"], tls["keyfile"])
        if role == "server" and service["connection"]:
            connection = service["connection"]
            private_file(connection["api_key_file"], limit=4096)
            _key_value(Path(connection["api_key_file"]).read_text(encoding="utf-8").strip())
            if connection["ca_file"]:
                ssl.create_default_context(cafile=connection["ca_file"])
        host = service["host"]
        family = socket.AF_INET6 if ":" in host else socket.AF_INET
        try:
            with socket.socket(family, socket.SOCK_STREAM) as probe:
                probe.bind((host, service["port"]))
        except OSError:
            raise SetupError(
                f"{role} bind address/port is unavailable; no existing service was stopped or reused."
            ) from None


def _wait_ready(process, service, timeout=15):
    host = service["host"]
    host = "127.0.0.1" if host in ("0.0.0.0", "localhost") else "::1" if host == "::" else host
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if process.poll() is not None:
            raise SetupError("A requested service exited during startup; see its console output.")
        try:
            with socket.create_connection((host, service["port"]), timeout=0.2):
                return
        except OSError:
            time.sleep(0.1)
    raise SetupError("A requested service did not become ready; see its console output.")


def launch_services(config, selected=None, *, popen=subprocess.Popen, ready=_wait_ready):
    commands = service_commands(config)
    selected = list(config["launch_roles"]) if selected is None else list(selected)
    if len(set(selected)) != len(selected) or any(role not in commands for role in selected):
        raise SetupError("Requested service is not configured.")
    if not selected:
        print("No services selected; configuration only.", flush=True)
        return 0
    preflight(config, selected)
    children = []
    previous = {}
    try:
        for name in ("SIGTERM", "SIGHUP", "SIGQUIT", "SIGINT"):
            number = getattr(signal, name, None)
            if number is not None:
                previous[number] = signal.signal(
                    number, lambda *_: (_ for _ in ()).throw(KeyboardInterrupt())
                )
        for role in selected:
            process = popen(
                commands[role], env=service_environment(config, role), start_new_session=True
            )
            children.append((role, process))
            ready(process, config["relay" if role == "relay" else "server"])
            print(
                f"{role} started (PID {process.pid}); Ctrl+C stops services started by this launcher.",
                flush=True,
            )
        while True:
            for _role, process in children:
                status = process.poll()
                if status is not None:
                    return status
            time.sleep(0.2)
    except KeyboardInterrupt:
        return 0
    finally:
        failures = []
        # Repeated terminal signals must not interrupt cleanup and orphan siblings.
        for number in previous:
            signal.signal(number, signal.SIG_IGN)
        try:
            for role, process in reversed(children):
                if process.poll() is not None:
                    continue
                try:
                    process.terminate()
                    try:
                        process.wait(timeout=10)
                    except subprocess.TimeoutExpired:
                        print(
                            f"{role} PID {process.pid} did not stop gracefully; stopping only this launcher-owned child.",
                            file=sys.stderr,
                        )
                        process.kill()
                        process.wait(timeout=5)
                except ProcessLookupError:
                    pass
                except (OSError, subprocess.TimeoutExpired):
                    failures.append(process.pid)
                    print(
                        f"Could not confirm shutdown of launcher-owned {role} PID {process.pid}; inspect it manually.",
                        file=sys.stderr,
                    )
        finally:
            for number, handler in previous.items():
                signal.signal(number, handler)
        if failures:
            raise SetupError("Some launcher-owned children could not be confirmed stopped.")


def write_launcher(config_path, config, console):
    check_output_paths(config_path, config)
    launcher = config_path.with_suffix(".run.sh")
    command = [
        str(Path(config["runtime_dir"]) / "venv/bin/python"),
        str(Path(config["source_dir"]) / "scripts/setup_wizard.py"),
        "--launch",
        str(config_path),
    ]
    text = (
        "#!/usr/bin/env bash\n"
        + GENERATED
        + "set -euo pipefail\nexec "
        + shlex.join(command)
        + ' "$@"\n'
    )
    replace = launcher.exists() or launcher.is_symlink()
    if replace:
        private_file(launcher)
        if launcher.read_text(encoding="utf-8") == text:
            return launcher
        if not console.yes("Replace the existing convenience launch script?", False):
            console.say(
                "Existing launch script kept; saved JSON configuration is available to setup."
            )
            return None
    write_private(launcher, text, replace=replace)
    launcher.chmod(0o700)
    return launcher


def runtime_entries(runtime_dir, pi):
    import shutil

    entries = [str(Path(runtime_dir) / "venv/bin"), str(Path(pi).parent)]
    node = shutil.which("node")
    if node:
        entries.append(str(Path(node).parent))
    return list(dict.fromkeys(entries))


def check_runtime(config):
    expected = Path(config["runtime_dir"]) / "venv"
    module = Path(config["source_dir"]) / "src/swarm/setup_wizard.py"
    if (
        Path(sys.prefix).resolve() != expected.resolve()
        or Path(__file__).resolve() != module.resolve()
    ):
        raise SetupError(
            "Saved runtime/source does not match this installation. Rerun setup to select/update it explicitly."
        )
    if not os.access(config["pi"], os.X_OK):
        raise SetupError("Saved Pi executable is unavailable. Rerun setup.")


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Interactive Swarm setup and saved-config launcher"
    )
    parser.add_argument("--runtime-dir", type=Path)
    parser.add_argument("--source-dir", type=Path)
    parser.add_argument("--pi", type=Path)
    parser.add_argument("--config", type=Path)
    parser.add_argument("--no-launch", action="store_true")
    parser.add_argument(
        "--launch", type=Path, help="explicitly launch the saved selection from this JSON file"
    )
    parser.add_argument(
        "--roles",
        nargs="+",
        choices=["relay", "server"],
        help="explicit role override when using --launch",
    )
    args = parser.parse_args(argv)
    console = Console()
    try:
        if args.launch:
            config = read_config(args.launch.expanduser().absolute())
            if args.no_launch:
                console.say("Saved configuration validated; no services launched.")
                return 0
            check_runtime(config)
            return launch_services(config, args.roles)
        if args.roles:
            raise SetupError("--roles requires --launch.")
        if not all((args.runtime_dir, args.source_dir, args.pi)):
            raise SetupError("Run setup_swarm.sh to provision/select the runtime first.")
        path = Path(
            absolute(
                str(args.config)
                if args.config
                else console.ask(
                    "Setup configuration JSON file", str(Path.home() / ".config/swarm/setup.json")
                )
            )
        )
        existing = path.exists() or path.is_symlink()
        config = None
        if existing:
            previous = read_config(path)
            if console.yes("Use saved configuration without reconfiguring?", True):
                config = previous
                current = {
                    "runtime_dir": str(args.runtime_dir.absolute()),
                    "source_dir": str(args.source_dir.absolute()),
                    "pi": str(args.pi.absolute()),
                }
                if any(config[key] != value for key, value in current.items()):
                    if not console.yes(
                        "Update saved runtime/source/Pi to the installation just provisioned?", True
                    ):
                        raise SetupError(
                            "Runtime mismatch; no old installation was launched or configuration changed."
                        )
                    config.update(current)
                    config["path_entries"] = runtime_entries(args.runtime_dir, args.pi)
            elif not console.yes(
                "Replace this configuration after answering setup questions?", False
            ):
                raise SetupError("Existing configuration was not changed.")
        if config is None:
            config = collect_config(
                console,
                runtime_dir=args.runtime_dir.absolute(),
                source_dir=args.source_dir.absolute(),
                pi=args.pi.absolute(),
                config_path=path,
            )
        selected = []
        if not args.no_launch:
            console.say(
                "Selected services stay foreground-supervised. Ctrl+C or terminal closure stops launcher-owned children, forcibly only if graceful shutdown times out."
            )
            if config["relay"] and console.yes("Start the configured local repeater now?", False):
                selected.append("relay")
            if config["server"] and console.yes("Start the configured Swarm server now?", False):
                selected.append("server")
            config["launch_roles"] = selected
        save_config(path, config, replace=existing)
        console.say(f"Configuration saved: {path}. Secret values are kept only in private files.")
        console.say(
            "Saved launch selection: "
            + (
                ", ".join(config["launch_roles"])
                or "none (use --roles explicitly for a later launch)"
            )
        )
        launcher = write_launcher(path, config, console)
        if launcher:
            console.say(f"Reusable launcher: {launcher}")
        console.say(
            "Pi provider credentials are not configured automatically. Authenticate in Pi before using model-backed agents."
        )
        if not selected:
            console.say("Setup complete; no services launched.")
            return 0
        check_runtime(config)
        return launch_services(config, selected)
    except (SetupError, OSError, ssl.SSLError, EOFError, ValueError) as error:
        message = (
            str(error)
            if isinstance(error, SetupError)
            else "Setup could not complete; check paths, permissions, TLS files and terminal input."
        )
        print("Swarm setup: " + message, file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print(
            "\nSetup cancelled; existing files were not overwritten without permission.",
            file=sys.stderr,
        )
        return 130
