#!/usr/bin/env bash
# Swarm Windows runtime (static, generated config in sibling env.sh / config.json).
#
# Sourced/generated env.sh exports all SWARM_* paths as Cygwin POSIX paths and
# extends PATH with the dedicated venv bin and the installation's bin/ (so the
# generated `pi` shim is discoverable when tmux launches agents).
#
# User argv is forwarded verbatim via "$@"; no string interpolation of args.
set -euo pipefail
# PowerShell launches a non-login Cygwin bash with only the inherited Windows
# PATH. Core utilities must be available before locating/sourcing env.sh.
export PATH="/usr/bin:/bin:$PATH"

__swarm_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# env.sh is generated by the installer and contains only trusted, shell-quoted
# exports. It is not user input.
if [ ! -f "$__swarm_dir/env.sh" ]; then
  echo "swarm: env.sh not found at \"$__swarm_dir/env.sh\". The install dir is" >&2
  echo "swarm: incomplete; re-run setup-windows.cmd / setup-windows.sh." >&2
  exit 3
fi
# shellcheck disable=SC1090,SC1091
. "$__swarm_dir/env.sh"

# Surface the config JSON location for downstream tooling.
export SWARM_WINDOWS_CONFIG="$__swarm_dir/config.json"

# Exec the Swarm CLI from the dedicated Cygwin venv (never the repo .venv).
# SWARM_VENV_PYTHON is a Cygwin POSIX path set by env.sh.
exec "$SWARM_VENV_PYTHON" -m swarm "$@"
